package agentservice

import (
	"context"
	"encoding/json"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"sync"
	"testing"
	"time"

	"radar/internal/protocol"
)

func TestCalendarScheduleNativeAdmissionLostResponseConcurrentTicksAndRestart(t *testing.T) {
	if _, err := exec.LookPath("node"); err != nil {
		t.Skip("Node 24 is required")
	}
	_, file, _, _ := runtime.Caller(0)
	repo := filepath.Clean(filepath.Join(filepath.Dir(file), "../.."))
	if _, err := os.Stat(filepath.Join(repo, "agent-host/node_modules/@earendil-works/pi-durable")); err != nil {
		t.Skip("install agent-host dependencies for native admission tests")
	}
	m, reg := collectionFixture(t)
	t.Setenv("RADAR_AGENT_HOST", filepath.Join(repo, "agent-host/src/runner.ts"))
	helper := filepath.Join(filepath.Dir(os.Getenv("RADAR_SOCKET")), "radar-helper")
	binding, _ := json.Marshal(reg.Workspace)
	if err := os.WriteFile(helper, []byte("#!/bin/sh\nprintf '%s\\n' '"+string(binding)+"'\n"), 0700); err != nil {
		t.Fatal(err)
	}
	t.Setenv("RADAR_BINARY", helper)
	dir, _ := instanceDir(reg.ID)
	reg.Entrypoint = filepath.Join(repo, "agent-host/examples/workday-check.ts")
	if err := atomicJSON(filepath.Join(dir, "registration.json"), reg); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "config.json"), []byte(`{"fixture":true}`), 0600); err != nil {
		t.Fatal(err)
	}
	clock := scheduleTime("2026-10-26T08:00:00Z")
	m.now = func() time.Time { return clock }
	configuredSchedule(t, m, reg, workdaySchedule())
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	if _, err := m.Handle(ctx, protocol.AgentRequest{Operation: "start", ID: reg.ID}); err != nil {
		t.Fatal(err)
	}
	defer func() { _, _ = m.Handle(context.Background(), protocol.AgentRequest{Operation: "stop", ID: reg.ID}) }()
	reg, _ = load(reg.ID)
	lost, restore := loseFirstScheduleResponse(t, reg)
	defer restore()
	clock = scheduleTime("2026-10-26T09:00:00Z")
	if err := m.tickSchedules(ctx, reg, clock, true); err == nil {
		t.Fatal("lost native response advanced checkpoint")
	}
	pendingBytes, err := os.ReadFile(schedulePath(reg))
	if err != nil {
		t.Fatal(err)
	}
	var committed struct {
		Result struct {
			TaskID     int       `json:"taskId"`
			AcceptedAt time.Time `json:"acceptedAt"`
		}
	}
	if err := json.Unmarshal(<-lost, &committed); err != nil || committed.Result.TaskID <= 0 {
		t.Fatalf("native admission failed: %+v %v", committed, err)
	}
	// Restart the producer with no in-memory event state. Concurrent ticks share
	// the same manager lock used by supervision and configuration.
	m = New(m.workspace)
	m.now = func() time.Time { return clock }
	var group sync.WaitGroup
	failures := make(chan error, 12)
	for range 12 {
		group.Go(func() {
			m.mu.Lock()
			defer m.mu.Unlock()
			if err := m.tickSchedules(ctx, reg, clock, true); err != nil {
				failures <- err
			}
		})
	}
	group.Wait()
	close(failures)
	for err := range failures {
		t.Fatal(err)
	}
	s := savedSchedule(t, reg)
	if s.Pending != nil || s.LastAdmission == nil || s.LastAdmission.TaskID != committed.Result.TaskID || !s.LastAdmission.AcceptedAt.Equal(committed.Result.AcceptedAt) {
		t.Fatalf("native receipt was duplicated: %+v", s)
	}
	restore()
	if _, err := m.Handle(ctx, protocol.AgentRequest{Operation: "stop", ID: reg.ID}); err != nil {
		t.Fatal(err)
	}
	if _, err := m.Handle(ctx, protocol.AgentRequest{Operation: "start", ID: reg.ID}); err != nil {
		t.Fatal(err)
	}
	// Model a crash before checkpoint persistence after a successful admission.
	if err := os.WriteFile(schedulePath(reg), pendingBytes, 0600); err != nil {
		t.Fatal(err)
	}
	if err := m.tickSchedules(ctx, reg, clock, true); err != nil {
		t.Fatal(err)
	}
	if a := savedSchedule(t, reg).LastAdmission; a == nil || a.TaskID != committed.Result.TaskID || !a.AcceptedAt.Equal(committed.Result.AcceptedAt) {
		t.Fatal("runner restart created a second native task")
	}
	deadline := time.Now().Add(5 * time.Second)
	for {
		data, err := m.Handle(ctx, protocol.AgentRequest{Operation: "inspect", ID: reg.ID})
		if err != nil {
			t.Fatal(err)
		}
		var status protocol.AgentStatus
		if err := json.Unmarshal(data, &status); err != nil {
			t.Fatal(err)
		}
		if status.Snapshot != nil && strings.Contains(status.Snapshot.Presentation.Summary, "Fixture daily check: 1 occurrence(s)") {
			if !strings.Contains(status.Snapshot.Presentation.Summary, "2026-10-26T09:00:00.000Z") {
				t.Fatal("definition did not receive intended observation window")
			}
			break
		}
		if time.Now().After(deadline) {
			t.Fatalf("fixture did not complete exactly once: %+v", status.Snapshot)
		}
		time.Sleep(20 * time.Millisecond)
	}
	// The next day is generated by the real supervisor, without manual ticks.
	clock = scheduleTime("2026-10-27T09:00:00Z")
	runCtx, stopRun := context.WithCancel(ctx)
	finished := make(chan struct{})
	go func() { defer close(finished); m.Run(runCtx, nil) }()
	defer func() { stopRun(); <-finished }()
	deadline = time.Now().Add(5 * time.Second)
	for {
		data, err := m.Handle(ctx, protocol.AgentRequest{Operation: "inspect", ID: reg.ID})
		if err != nil {
			t.Fatal(err)
		}
		var status protocol.AgentStatus
		if err := json.Unmarshal(data, &status); err != nil {
			t.Fatal(err)
		}
		if status.Snapshot != nil && strings.Contains(status.Snapshot.Presentation.Summary, "Fixture daily check: 2 occurrence(s)") {
			if status.Schedules[0].LastAdmission == nil || !status.Schedules[0].LastAdmission.ScheduledAt.Equal(clock) {
				t.Fatal("supervisor admission not inspectable")
			}
			break
		}
		if time.Now().After(deadline) {
			t.Fatalf("supervisor did not deliver the next workday: %+v", status.Snapshot)
		}
		time.Sleep(20 * time.Millisecond)
	}
}
