const tapContent = (version: string) => ({ type: "file", encoding: "base64", content: Buffer.from(formula(version)).toString("base64"), sha: "a".repeat(40) });
const platforms = ["darwin_arm64", "linux_amd64", "linux_arm64"];
const release = (version: string) => ({
  tag_name: version, draft: false, prerelease: false,
  assets: ["release.json", "release.json.sig", ...platforms.map(platform => `radar_${version}_${platform}.tar.gz`)]
    .map(name => ({ name, size: 123, state: "uploaded" })),
});
const manifest = (version: string) => ({ schema: 1, version, artifacts: Object.fromEntries(platforms.map(platform => [platform === "darwin_arm64" ? "arm64" : platform, { file: `radar_${version}_${platform}.tar.gz` }])) });

function fixture(version = "v1.2.3", current = "v1.2.2") {
  const routes = new Map<string, { status?: number; data: unknown }>([
    [`${tapFile}?ref=main`, { data: tapContent(current) }],
    [releaseList, { data: [release(version)] }],
    [manifestURL(version), { data: manifest(version) }],
    [npmURL(version), { data: { name: npmPackage, version: version.slice(1) } }],
  ]);
  const calls: { url: string; method: string; options: RequestInit }[] = [];
  const request = automationClient("fixture-token", async (url: string, options: RequestInit) => {
    calls.push({ url, method: options.method ?? "GET", options });
    const response = routes.get(url);
    assert.ok(response, `unexpected HTTP request: ${url}`);
    return new Response(JSON.stringify(response.data), { status: response.status ?? 200 });
  });
  return { routes, calls, request };
}

