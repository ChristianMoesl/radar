const npmPackage = "@christianmoesl/pi-radar";
const manifestURL = (version: string) => `https://github.com/ChristianMoesl/radar/releases/download/${version}/release.json`;
const npmURL = (version: string) => `https://registry.npmjs.org/${encodeURIComponent(npmPackage)}/${version.slice(1)}`;
