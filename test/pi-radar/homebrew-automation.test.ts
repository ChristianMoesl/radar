import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import test from "node:test";
// @ts-expect-error Plain Node release tooling has no TypeScript declarations.
import { automationClient, formulaVersion, prepareUpdate, publishUpdate } from "../../scripts/homebrew/automation.mjs";

const exec = promisify(execFile);
const root = fileURLToPath(new URL("../../", import.meta.url));
const api = "https://api.github.com";
const tapFile = `${api}/repos/ChristianMoesl/homebrew-tap/contents/Formula/radar.rb`;
const releaseList = `${api}/repos/ChristianMoesl/radar/releases?per_page=100&page=1`;
const npmPackage = "@christianmoesl/pi-radar";
const manifestURL = (version: string) => `https://github.com/ChristianMoesl/radar/releases/download/${version}/release.json`;
const npmURL = (version: string) => `https://registry.npmjs.org/${encodeURIComponent(npmPackage)}/${version.slice(1)}`;
const formula = (version: string) => `# Generated by radar/scripts/homebrew; review before publishing to ChristianMoesl/homebrew-tap.\nclass Radar < Formula\n  version "${version.slice(1)}"\nend\n`;
const tapContent = (version: string) => ({ type: "file", encoding: "base64", content: Buffer.from(formula(version)).toString("base64"), sha: "a".repeat(40) });
const platforms = ["darwin_arm64", "linux_amd64", "linux_arm64"];
const release = (version: string) => ({
  tag_name: version, draft: false, prerelease: false,
  assets: ["release.json", "release.json.sig", ...platforms.map(platform => `radar_${version}_${platform}.tar.gz`)]
    .map(name => ({ name, size: 123, state: "uploaded" })),
});
const manifest = (version: string) => ({ schema: 1, version, artifacts: Object.fromEntries(platforms.map(platform => [platform === "darwin_arm64" ? "arm64" : platform, { file: `radar_${version}_${platform}.tar.gz` }])) });

function fixture(version = "v1.2.3", current = "v1.2.2") {
  const routes = new Map<string, { status?: number; data: unknown }>([
    [`${tapFile}?ref=main`, { data: tapContent(current) }],
    [releaseList, { data: [release(version)] }],
    [manifestURL(version), { data: manifest(version) }],
    [npmURL(version), { data: { name: npmPackage, version: version.slice(1) } }],
    [tapFile, { data: { commit: { sha: "b".repeat(40) } } }],
  ]);
  const calls: { url: string; method: string; options: RequestInit }[] = [];
  const request = automationClient("fixture-token", async (url: string, options: RequestInit) => {
    calls.push({ url, method: options.method ?? "GET", options });
    const response = routes.get(url);
    assert.ok(response, `unexpected HTTP request: ${url}`);
    return new Response(JSON.stringify(response.data), { status: response.status ?? 200 });
  });
  return { routes, calls, request };
}

test("readiness selects an all-platform release only after exact npm approval without any writes", async () => {
  const f = fixture();
  const decision = await prepareUpdate(f.request);
  assert.equal(decision.ready, true);
  assert.equal(decision.version, "v1.2.3");
  assert.ok(f.calls.every(call => call.method === "GET"));
  for (const call of f.calls) {
    const authorization = new Headers(call.options.headers).get("Authorization");
    assert.equal(authorization, call.url.startsWith(`${api}/`) ? "Bearer fixture-token" : null);
  }
});

for (const reason of ["npm staged", "old macOS manifest", "missing archive", "unfinished archive", "duplicate archive", "already published", "draft", "prerelease"]) {
  test(`readiness skips ${reason}`, async () => {
    const f = fixture();
    if (reason === "npm staged") f.routes.set(npmURL("v1.2.3"), { status: 404, data: {} });
    if (reason === "old macOS manifest") f.routes.set(manifestURL("v1.2.3"), { data: { ...manifest("v1.2.3"), artifacts: { arm64: manifest("v1.2.3").artifacts.arm64 } } });
    const item = release("v1.2.3");
    if (reason === "missing archive") item.assets.pop();
    if (reason === "unfinished archive") item.assets[2].state = "new";
    if (reason === "duplicate archive") item.assets.push(item.assets[2]);
    if (reason === "draft") item.draft = true;
    if (reason === "prerelease") item.prerelease = true;
    f.routes.set(releaseList, { data: [item] });
    if (reason === "already published") f.routes.set(`${tapFile}?ref=main`, { data: tapContent("v1.2.3") });
    assert.equal((await prepareUpdate(f.request)).ready, false);
    assert.ok(f.calls.every(call => call.method === "GET"));
    if (reason !== "npm staged") assert.ok(!f.calls.some(call => call.url.includes("registry.npmjs.org")));
  });
}

test("semantic ordering and pending newer npm approval preserve the latest coordinated candidate", async () => {
  const f = fixture("v1.9.0", "v1.8.0");
  f.routes.set(releaseList, { data: [release("v1.9.0"), release("v1.10.0")] });
  f.routes.set(manifestURL("v1.10.0"), { data: manifest("v1.10.0") });
  f.routes.set(npmURL("v1.10.0"), { status: 404, data: {} });
  assert.equal((await prepareUpdate(f.request)).version, "v1.9.0");
  const newer = f.calls.findIndex(call => call.url === npmURL("v1.10.0"));
  const older = f.calls.findIndex(call => call.url === npmURL("v1.9.0"));
  assert.ok(newer >= 0 && newer < older);
  f.routes.set(npmURL("v1.10.0"), { data: { name: npmPackage, version: "1.10.0" } });
  assert.equal((await prepareUpdate(f.request)).version, "v1.10.0");
});

test("release pagination is bounded and includes later pages", async () => {
  const f = fixture();
  f.routes.set(releaseList, { data: Array.from({ length: 100 }, () => release("v1.0.0")) });
  f.routes.set(`${api}/repos/ChristianMoesl/radar/releases?per_page=100&page=2`, { data: [release("v1.2.3")] });
  assert.equal((await prepareUpdate(f.request)).version, "v1.2.3");
});

test("manual dispatch can revalidate an already published version; publication remains idempotent", async () => {
  const f = fixture("v1.2.3", "v1.2.3");
  assert.equal((await prepareUpdate(f.request, "v1.2.3")).ready, true);
  assert.equal((await publishUpdate(f.request, "v1.2.3", formula("v1.2.3"))).published, false);
  assert.ok(!f.calls.some(call => call.method === "PUT"));
});

for (const reason of ["wrong npm version", "wrong npm name", "API failure", "unknown tag", "malformed tap"]) {
  test(`readiness fails safely for ${reason}`, async () => {
    const f = fixture();
    let requested = "";
    if (reason === "wrong npm version") f.routes.set(npmURL("v1.2.3"), { data: { name: npmPackage, version: "1.2.4" } });
    if (reason === "wrong npm name") f.routes.set(npmURL("v1.2.3"), { data: { name: "other", version: "1.2.3" } });
    if (reason === "API failure") f.routes.set(releaseList, { status: 403, data: {} });
    if (reason === "unknown tag") requested = "v1.2.4";
    if (reason === "malformed tap") f.routes.set(`${tapFile}?ref=main`, { data: { ...tapContent("v1.2.2"), content: Buffer.from("invalid formula").toString("base64") } });
    await assert.rejects(prepareUpdate(f.request, requested));
    assert.ok(!f.calls.some(call => call.method === "PUT"));
  });
}

for (const version of ["1.2.3", "v1.2.3-rc.1", "v01.2.3", "v1.2.3\n", "v1.2.3\r\n", "v1.2.3\nready=true"]) {
  test(`readiness rejects unsafe version ${JSON.stringify(version)} before any HTTP request`, async () => {
    const f = fixture();
    await assert.rejects(prepareUpdate(f.request, version), /stable vX.Y.Z/);
    assert.equal(f.calls.length, 0);
  });
}

test("publisher appends exactly the authenticated candidate to tap main using the expected file SHA", async () => {
  const f = fixture();
  const candidate = formula("v1.2.3");
  assert.equal((await publishUpdate(f.request, "v1.2.3", candidate)).published, true);
  const writes = f.calls.filter(call => call.method === "PUT");
  assert.equal(writes.length, 1);
  assert.equal(writes[0].url, tapFile);
  assert.deepEqual(JSON.parse(String(writes[0].options.body)), {
    message: "chore: update Radar to v1.2.3", content: Buffer.from(candidate).toString("base64"),
    sha: "a".repeat(40), branch: "main",
  });
});

for (const current of ["v1.2.3", "v1.3.0"]) {
  test(`publisher never overwrites or downgrades ${current}`, async () => {
    const f = fixture("v1.2.3", current);
    assert.equal((await publishUpdate(f.request, "v1.2.3", formula("v1.2.3"))).published, false);
    assert.ok(!f.calls.some(call => call.method === "PUT"));
  });
}

for (const status of [409, 403]) {
  test(`publisher fails closed on concurrent updates or branch restrictions (HTTP ${status})`, async () => {
    const f = fixture();
    f.routes.set(tapFile, { status, data: {} });
    await assert.rejects(publishUpdate(f.request, "v1.2.3", formula("v1.2.3")), new RegExp(`HTTP ${status}`));
    assert.equal(f.calls.filter(call => call.method === "PUT").length, 1);
  });
}

test("publisher rejects wrong-version or local smoke artifacts before reading the tap", async () => {
  const f = fixture();
  for (const candidate of [formula("v1.2.4"), formula("v1.2.3").replace("# Generated by radar/scripts/homebrew;", "# LOCAL CI SMOKE FIXTURE ONLY")]) {
    await assert.rejects(publishUpdate(f.request, "v1.2.3", candidate), /not the generated formula/);
  }
  assert.equal(f.calls.length, 0);
  assert.throws(() => formulaVersion('  version "1.2.3"\n  version "1.2.4"'), /one explicit version/);
});

test("unconfigured scheduled automation skips without network access or publication", async t => {
  const dir = await mkdtemp(join(tmpdir(), "radar-homebrew-readiness-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const output = join(dir, "output");
  const { stdout } = await exec(process.execPath, ["scripts/homebrew/automation.mjs", "prepare"], {
    cwd: root, env: { ...process.env, GH_TOKEN: "", GITHUB_EVENT_NAME: "schedule", TAP_TOKEN_CONFIGURED: "false", GITHUB_OUTPUT: output, GITHUB_STEP_SUMMARY: join(dir, "summary") },
  });
  assert.match(stdout, /disabled until.*HOMEBREW_TAP_TOKEN/);
  assert.equal(await readFile(output, "utf8"), "ready=false\nversion=\nauto_publish=false\n");
  await assert.rejects(exec(process.execPath, ["scripts/homebrew/automation.mjs", "publish", "v1.2.3", "unused"], { cwd: root, env: { ...process.env, GH_TOKEN: "" } }), /HOMEBREW_TAP_TOKEN is required/);
});

test("manual dispatch still produces a candidate without a publication token", async t => {
  const dir = await mkdtemp(join(tmpdir(), "radar-homebrew-manual-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const { routes } = fixture();
  const preload = join(dir, "mock-http.mjs");
  const calls = join(dir, "calls");
  await writeFile(preload, `import { appendFileSync } from 'node:fs';
const routes = new Map(${JSON.stringify([...routes])});
globalThis.fetch = async (url, options) => {
  appendFileSync(process.env.FIXTURE_CALLS, (options.method ?? 'GET') + '\\n');
  const response = routes.get(url);
  if (!response) throw new Error('Unexpected fixture URL: ' + url);
  return new Response(JSON.stringify(response.data), { status: response.status ?? 200 });
};\n`);
  const output = join(dir, "output");
  const { stdout } = await exec(process.execPath, ["--import", preload, "scripts/homebrew/automation.mjs", "prepare"], {
    cwd: root, env: { ...process.env, GH_TOKEN: "fixture-read-token", GITHUB_EVENT_NAME: "workflow_dispatch", TAP_TOKEN_CONFIGURED: "false", REQUESTED_VERSION: "v1.2.3", GITHUB_OUTPUT: output, GITHUB_STEP_SUMMARY: join(dir, "summary"), FIXTURE_CALLS: calls },
  });
  assert.equal(await readFile(output, "utf8"), "ready=true\nversion=v1.2.3\nauto_publish=false\n");
  assert.match(stdout, /downloadable formula remain available, but publication is skipped/);
  assert.ok((await readFile(calls, "utf8")).trim().split("\n").every(method => method === "GET"));
});

test("the publication reauthentication shell rejects changed artifacts and stale releases", async t => {
  const workflow = await readFile(join(root, ".github/workflows/homebrew.yml"), "utf8");
  const lines = workflow.split("\n");
  const start = lines.findIndex(line => line.includes("- name: Reauthenticate the validated candidate"));
  assert.ok(start >= 0);
  const run = lines.findIndex((line, index) => index > start && line === "        run: |");
  const commands: string[] = [];
  for (const line of lines.slice(run + 1)) {
    if (!line.startsWith("          ")) break;
    commands.push(line.slice(10));
  }
  assert.ok(commands.length > 0);
  const dir = await mkdtemp(join(tmpdir(), "radar-homebrew-reauthenticate-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const bin = join(dir, "bin");
  const candidate = join(dir, "build/homebrew/Formula/radar.rb");
  await mkdir(bin);
  await mkdir(join(dir, "build/release-source"), { recursive: true });
  await mkdir(join(dir, "build/homebrew/Formula"), { recursive: true });
  const original = formula("v1.2.3");
  const generated = join(dir, "generated.rb");
  await writeFile(generated, original);
  await writeFile(join(bin, "go"), `#!/bin/sh
[ "$*" = 'run ./scripts/homebrew v1.2.3' ] || exit 7
[ "$FIXTURE_STATUS" != stale ] || exit 1
cat "$FIXTURE_GENERATED"
`, { mode: 0o755 });
  for (const scenario of ["match", "changed artifact", "stale"]) {
    const bytes = scenario === "changed artifact" ? original + "# changed after native tests\n" : original;
    await writeFile(candidate, bytes);
    const promise = exec("bash", ["-e", "-u", "-o", "pipefail", "-c", commands.join("\n")], {
      cwd: dir, env: { PATH: `${bin}:/usr/bin:/bin`, RELEASE_VERSION: "v1.2.3", FIXTURE_STATUS: scenario, FIXTURE_GENERATED: generated },
    });
    if (scenario === "match") await promise;
    else await assert.rejects(promise);
    assert.equal(await readFile(candidate, "utf8"), bytes);
  }
});

test("publication waits for the whole native matrix and reauthenticates the exact artifact before receiving the tap token", async () => {
  const workflow = await readFile(join(root, ".github/workflows/homebrew.yml"), "utf8");
  assert.match(workflow, /cron: '\*\/15 \* \* \* \*'/);
  assert.match(workflow, /cancel-in-progress: false/);
  assert.match(workflow, /needs: \[prepare, formula\]/);
  assert.match(workflow, /needs\.prepare\.outputs\.auto_publish == 'true'/);
  assert.match(workflow, /github\.ref == 'refs\/heads\/main'/);
  const reauthenticate = workflow.indexOf("- name: Reauthenticate the validated candidate");
  const write = workflow.indexOf("- name: Publish a normal tap commit");
  assert.ok(reauthenticate >= 0 && reauthenticate < write);
  assert.ok(workflow.slice(reauthenticate, write).includes("go run ./scripts/homebrew"));
  assert.ok(workflow.slice(reauthenticate, write).includes("cmp build/homebrew/Formula/radar.rb build/homebrew/verified.rb"));
  assert.ok(!workflow.slice(0, write).includes("GH_TOKEN: ${{ secrets.HOMEBREW_TAP_TOKEN }}"));
  assert.ok(workflow.slice(write).includes("GH_TOKEN: ${{ secrets.HOMEBREW_TAP_TOKEN }}"));
  assert.match(workflow, /contents: read/);
  assert.ok(!workflow.includes("contents: write"));
});
